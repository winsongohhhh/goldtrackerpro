type Translations = Record<keyof typeof translations['en'], string>;

interface I18nContextType {
  lang: Language;
  setLang: (lang: Language) => void;
  t: Translations;
}

const I18nContext = createContext<I18nContextType | null>(null);

function getInitialLanguage(): Language {
  const savedLanguage = localStorage.getItem('gold-lang');
  if (savedLanguage === 'en' || savedLanguage === 'cn') return savedLanguage;

  const browserLanguage = typeof navigator === 'undefined' ? '' : navigator.language;
  return /^zh(?:-|$)/i.test(browserLanguage) ? 'cn' : 'en';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Language>(getInitialLanguage);

  const handleSetLang = (l: Language) => {
    setLang(l);
    localStorage.setItem('gold-lang', l);
  };

  return (
    <I18nContext.Provider value={{ lang, setLang: handleSetLang, t: translations[lang] }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}
